"""
Model evaluation — the ONLY source of the metrics the website displays.

Run:  npm run ml:evaluate   (or: python ml/evaluation/evaluate.py)

Writes ml/models/v<N>/metrics.json and copies it to ml/models/metrics.json,
which is what the API serves to the AI / Predictive Intelligence page.

RULES ENCODED HERE
  * Metrics are computed on the TEST split only — episodes the model has never
    seen, from simulation runs that contributed to neither training nor model
    selection.
  * If the test split is too small or a class is unrepresented, the affected
    numbers are emitted as null with an explicit note. The UI renders that note
    verbatim instead of inventing a figure.
  * `trained_on_synthetic_data` is always true here and is surfaced next to
    every number in the UI.
  * Nothing in this file hard-codes a metric value.
"""

from __future__ import annotations

import json
import os
import shutil
import sys
from datetime import datetime, timezone

import numpy as np
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
import joblib

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from features.feature_engineering import (  # noqa: E402
    FEATURE_ORDER,
    MODEL_DIR,
    describe_split,
    load_dataset,
    split_by_episode,
)
from models.model_registry import get_current  # noqa: E402

# Below this many held-out rows, or this many rows for a given class, we do not
# claim a performance figure.
MIN_TEST_ROWS = 500
MIN_CLASS_SUPPORT = 20

INSUFFICIENT_NOTE = "Validation data insufficient for production performance metrics."

SYNTHETIC_CAVEAT = (
    "Model trained on SYNTHETIC telemetry generated by GridSync's own physics "
    "simulator. These metrics measure how separable the simulated scenario "
    "regimes are. They are NOT validated real-world fault-detection performance "
    "and must not be cited as such. Replace with metrics from labelled hardware "
    "telemetry before making any performance claim."
)


def main() -> int:
    print("=" * 70)
    print("GridSync — model evaluation (held-out test split)")
    print("=" * 70)

    current = get_current()
    if current is None:
        print("\nNo trained model found. Run:  npm run ml:train")
        return 1

    if not os.path.exists(current.model_joblib):
        print(f"\nModel artefact missing at {current.model_joblib}")
        return 1

    model = joblib.load(current.model_joblib)
    df = load_dataset()
    # Same random_state as training, so the identical episode split is restored
    # and the test episodes really are ones the model never saw.
    ds = split_by_episode(df)

    print(f"\nModel version: {current.version}")
    print(describe_split(ds))

    y_true = ds.y_test
    y_pred = model.predict(ds.X_test)
    labels = sorted(set(ds.y_train.tolist()) | set(y_true.tolist()))

    enough_rows = len(y_true) >= MIN_TEST_ROWS

    if enough_rows:
        accuracy = float(accuracy_score(y_true, y_pred))
        macro_precision = float(precision_score(y_true, y_pred, average="macro", zero_division=0))
        macro_recall = float(recall_score(y_true, y_pred, average="macro", zero_division=0))
        macro_f1 = float(f1_score(y_true, y_pred, average="macro", zero_division=0))
    else:
        accuracy = macro_precision = macro_recall = macro_f1 = None

    report = classification_report(
        y_true, y_pred, labels=labels, output_dict=True, zero_division=0
    )

    per_class: dict[str, dict] = {}
    underpowered: list[str] = []
    for label in labels:
        stats = report.get(label, {})
        support = int(stats.get("support", 0))
        if support < MIN_CLASS_SUPPORT:
            # Not enough held-out examples to characterise this class honestly.
            underpowered.append(label)
            per_class[label] = {
                "precision": None,
                "recall": None,
                "f1": None,
                "support": support,
                "note": f"Support {support} below minimum {MIN_CLASS_SUPPORT}; metrics withheld.",
            }
        else:
            per_class[label] = {
                "precision": round(float(stats.get("precision", 0.0)), 4),
                "recall": round(float(stats.get("recall", 0.0)), 4),
                "f1": round(float(stats.get("f1-score", 0.0)), 4),
                "support": support,
            }

    cm = confusion_matrix(y_true, y_pred, labels=labels).tolist()

    importances = sorted(
        (
            {"feature": name, "importance": round(float(imp), 6)}
            for name, imp in zip(FEATURE_ORDER, model.feature_importances_)
        ),
        key=lambda d: d["importance"],
        reverse=True,
    )

    notes: list[str] = [SYNTHETIC_CAVEAT]
    if not enough_rows:
        notes.append(
            f"{INSUFFICIENT_NOTE} Held-out test rows: {len(y_true)} (minimum {MIN_TEST_ROWS})."
        )
    if underpowered:
        notes.append(
            "Per-class metrics withheld for insufficient held-out support: "
            + ", ".join(underpowered)
        )

    metrics = {
        "modelVersion": current.version,
        "trainedAt": datetime.now(timezone.utc).isoformat(),
        "algorithm": "RandomForestClassifier (scikit-learn)",
        "trainedOnSyntheticData": True,
        "datasetSize": int(len(df)),
        "trainSize": int(len(ds.y_train)),
        "validationSize": int(len(ds.y_val)),
        "testSize": int(len(y_true)),
        "splitStrategy": (
            "Grouped by simulation episode and stratified by scenario: episodes are "
            "bucketed per scenario and divided 60/20/20, so no episode spans two "
            "splits (preventing leakage between autocorrelated neighbouring rows) "
            "while every scenario is represented in all three splits."
        ),
        "accuracy": round(accuracy, 4) if accuracy is not None else None,
        "macroPrecision": round(macro_precision, 4) if macro_precision is not None else None,
        "macroRecall": round(macro_recall, 4) if macro_recall is not None else None,
        "macroF1": round(macro_f1, 4) if macro_f1 is not None else None,
        "perClass": per_class,
        "confusionMatrix": cm,
        "labels": labels,
        "featureImportances": importances,
        "notes": notes,
    }
    if not enough_rows:
        metrics["insufficientDataNote"] = INSUFFICIENT_NOTE

    with open(current.metrics_json, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)
        f.write("\n")

    # Publish to the stable, committed location the runtime reads.
    current_dir = os.path.join(MODEL_DIR, "current")
    os.makedirs(current_dir, exist_ok=True)
    shutil.copyfile(current.metrics_json, os.path.join(current_dir, "metrics.json"))
    shutil.copyfile(current.metrics_json, os.path.join(MODEL_DIR, "metrics.json"))

    # ---- report ----------------------------------------------------------
    print("\n" + "-" * 70)
    print("HELD-OUT TEST RESULTS")
    print("-" * 70)
    if enough_rows:
        print(f"  Accuracy        : {accuracy:.4f}")
        print(f"  Macro precision : {macro_precision:.4f}")
        print(f"  Macro recall    : {macro_recall:.4f}")
        print(f"  Macro F1        : {macro_f1:.4f}")
    else:
        print(f"  {INSUFFICIENT_NOTE}")

    print("\n  Per class:")
    print(f"    {'class':<22} {'prec':>7} {'recall':>8} {'f1':>7} {'support':>8}")
    for label in labels:
        s = per_class[label]
        if s["precision"] is None:
            print(f"    {label:<22} {'--':>7} {'--':>8} {'--':>7} {s['support']:>8}")
        else:
            print(
                f"    {label:<22} {s['precision']:>7.3f} {s['recall']:>8.3f} "
                f"{s['f1']:>7.3f} {s['support']:>8}"
            )

    print("\n  Top features:")
    for row in importances[:8]:
        print(f"    {row['feature']:<22} {row['importance']:.4f}")

    print("\n" + "!" * 70)
    print(SYNTHETIC_CAVEAT)
    print("!" * 70)
    print(f"\nWrote {current.metrics_json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
